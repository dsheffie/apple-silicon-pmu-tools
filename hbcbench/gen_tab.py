#!/usr/bin/env python3
"""Generate tabbench.S: b.cond / bc.cond kernel pairs plus a table for tabbench.c.

Kernel ABI: void k(long iters, const uint8_t *bits); bits = 1 MiB of random 0/1.
Table entries: {name, b kernel, bc kernel, iterations, static test branches/iter}.

knee sweep  tkN: N static always-taken branches per iteration (as gen_hbc.py's
            tk kernels), at many N around the taken-branch capacity knees.

pollution   polG_F: G groups per iteration, each a "hard" pair followed by F
            filler branches. The hard pair is
                ldrb w13, [x1, x14]   (random bit, 1 MiB stream)
                cbz  w13, A           (A: random, unpredictable)
                cbz  w13, B           (B: same condition, predictable only
                                       from history, i.e. needs tagged state)
            and always uses cbz, identical in both variants, leaving the flags
            (Z=1) to the filler. Filler branches have random fixed directions
            (b.eq / b.ne) and are the only code that differs: b.cond vs bc.cond.
            If bc keeps the filler out of history-indexed predictor tables, the
            B branches mispredict less and the bc variant runs faster.
"""
import random
import sys

KNEE = [128, 192, 256, 320, 384, 448, 512, 640, 768, 896, 1024, 1152, 1280, 1536,
        1792, 2048, 2560, 3072, 4096, 6144, 8192]
POLLUTION = [(1024, f) for f in (0, 1, 2, 4, 8, 16, 32, 64, 256)] + \
            [(4096, f) for f in (4, 16, 64)]


def func(name, body):
    return f"\t.globl _{name}\n\t.p2align 6\n_{name}:\n{body}\tret\n\n"


def loop(body):
    # Long-range loop control (bodies can exceed b.cond/cbnz's +-1 MiB range).
    return ("\tcmp xzr, xzr\n\tmov x14, #0\n1:\n" + body +
            "\tsub x0, x0, #1\n\tcbz x0, 8f\n\tb 1b\n8:\n")


def tk(br, n):
    return loop("".join(f"\t{br}.eq 3{i % 2}f\n\tadd x10, x10, #1\n3{i % 2}:\n" for i in range(n)))


def pol(br, g, f, rng, with_b=True):
    # with_b=False is the matched control (polA): B replaced by two adds.
    hb = "\tcbz w13, 5f\n\tadd x11, x11, #1\n5:\n" if with_b else "\tadd x11, x11, #1\n\tadd x11, x11, #1\n"
    body = []
    for _ in range(g):
        body.append("\tldrb w13, [x1, x14]\n\tadd x14, x14, #1\n\tand x14, x14, #0xfffff\n"
                    "\tcbz w13, 4f\n\tadd x10, x10, #1\n4:\n" + hb)
        for _ in range(f):
            body.append(f"\t{br}.{'eq' if rng.random() < 0.5 else 'ne'} 3f\n\tadd x12, x12, #1\n3:\n")
    return loop("".join(body))


def hard_a_only(g):
    # Diagnostic (identical in both variants): the A branch alone, no B.
    return loop("\tldrb w13, [x1, x14]\n\tadd x14, x14, #1\n\tand x14, x14, #0xfffff\n"
                "\tcbz w13, 4f\n\tadd x10, x10, #1\n4:\n" * g)


def main():
    order = ("bc", "b") if "--bc-first" in sys.argv else ("b", "bc")
    src = ["// Generated by gen_tab.py; do not edit.\n\t.text\n"]
    for br in order:
        for n in KNEE:
            src.append(func(f"t_{br}_tk{n}", tk(br, n)))
        for g, f in POLLUTION:
            # Same filler directions in both variants.
            src.append(func(f"t_{br}_pol{g}_{f}", pol(br, g, f, random.Random(g * 1000 + f))))
            src.append(func(f"t_{br}_polA{g}_{f}", pol(br, g, f, random.Random(g * 1000 + f), False)))
        src.append(func(f"t_{br}_diagA1024", hard_a_only(1024)))
    entries = [("diagA1024", (16 << 20) // 2048, 1024)]
    entries += [(f"tk{n}", max(1, (64 << 20) // n), n) for n in KNEE]
    entries += [(f"pol{g}_{f}", max(1, (16 << 20) // (g * (f + 2))), g * (f + 2))
                for g, f in POLLUTION]
    entries += [(f"polA{g}_{f}", max(1, (16 << 20) // (g * (f + 2))), g * (f + 1))
                for g, f in POLLUTION]
    src.append("\t.section __TEXT,__cstring\n")
    for name, _, _ in entries:
        src.append(f"Ln_{name}:\n\t.asciz \"{name}\"\n")
    src.append("\t.section __DATA,__data\n\t.p2align 3\n\t.globl _tab_count\n"
               f"_tab_count:\n\t.quad {len(entries)}\n\t.globl _tab\n_tab:\n")
    for name, iters, nbr in entries:
        src.append(f"\t.quad Ln_{name}, _t_b_{name}, _t_bc_{name}, {iters}, {nbr}\n")
    sys.stdout.write("".join(src))


if __name__ == "__main__":
    main()
