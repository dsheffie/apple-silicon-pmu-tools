#!/usr/bin/env python3
"""Generate hbcbench.S: paired b.cond / bc.cond (FEAT_HBC) branch kernels.

Every kernel exists twice, identical except for the conditional-branch
mnemonic, so any timing difference is due to the "branch consistent" hint.
Kernel ABI: void k(long iters, const uint8_t *bits); x0 = iterations,
x1 = 64 KiB buffer of 0/1 bytes for the data-dependent kernels.
Loop control uses sub+cbnz so the condition flags belong to the test branch.
"""
import sys

FOOTPRINTS = [1024, 4096, 16384, 65536]


def func(name, body):
    return f"\t.globl _{name}\n\t.p2align 6\n_{name}:\n{body}\tret\n\n"


def kernels(br):
    out = []
    # 1. One never-taken branch per iteration (flags: Z=1, so b.ne never taken).
    out.append(func(f"k_{br}_single", f"""\tcmp xzr, xzr
1:\t{br}.ne 2f
\tadd x10, x10, #1
\tsub x0, x0, #1
\tcbnz x0, 1b
2:
"""))
    # 2. N static never-taken branches per iteration, one add between each.
    for n in FOOTPRINTS:
        body = "\tcmp xzr, xzr\n1:\n"
        body += f"\t{br}.ne 9f\n\tadd x10, x10, #1\n" * n
        body += "\tsub x0, x0, #1\n\tcbnz x0, 1b\n9:\n"
        out.append(func(f"k_{br}_fp{n}", body))
    # 2b. N static always-taken branches (Z=1, b.eq), each skipping one add:
    #     every branch needs a target-buffer entry, so large N stresses the
    #     predictor's capacity, which is where a "consistent" hint could help.
    for n in FOOTPRINTS:
        body = "\tcmp xzr, xzr\n1:\n"
        body += "".join(f"\t{br}.eq 3{i % 2}f\n\tadd x10, x10, #1\n3{i % 2}:\n" for i in range(n))
        body += "\tsub x0, x0, #1\n\tcbnz x0, 1b\n"
        out.append(func(f"k_{br}_tk{n}", body))
    # 3a. Alternating taken / not-taken (learnable from global history).
    out.append(func(f"k_{br}_alt", f"""1:\teor x11, x11, #1
\tcmp x11, #0
\t{br}.ne 2f
\tadd x10, x10, #1
2:\tsub x0, x0, #1
\tcbnz x0, 1b
"""))
    # 3b. Taken once every 8 iterations (period-8 pattern).
    out.append(func(f"k_{br}_p8", f"""1:\tadd x12, x12, #1
\tand x13, x12, #7
\tcmp x13, #0
\t{br}.eq 2f
\tadd x10, x10, #1
2:\tsub x0, x0, #1
\tcbnz x0, 1b
"""))
    # 4. Data-dependent: branch on bytes from a 64 KiB buffer (random 50/50 or
    #    95/5 depending on what the driver loads into it).
    out.append(func(f"k_{br}_data", f"""\tmov x14, #0
1:\tldrb w13, [x1, x14]
\tadd x14, x14, #1
\tand x14, x14, #0xffff
\tcmp w13, #0
\t{br}.ne 2f
\tadd x10, x10, #1
2:\tsub x0, x0, #1
\tcbnz x0, 1b
"""))
    return out


def main():
    src = ["// Generated by gen_hbc.py; do not edit.\n\t.text\n"]
    order = ("bc", "b") if "--bc-first" in sys.argv else ("b", "bc")
    for br in order:
        src += kernels(br)
    sys.stdout.write("".join(src))


if __name__ == "__main__":
    main()
