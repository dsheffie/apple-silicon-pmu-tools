#!/usr/bin/env python3
"""Generate coldbench.S: large-footprint / cold-code b.cond vs bc.cond regions.

Each region is straight-line code of NMAX conditional branches, every branch
with a fixed direction (so all of them are "consistent" in the FEAT_HBC sense).
The condition flags are set once (cmp xzr, xzr: Z=1) by the _hbc_enter
trampoline, so b.eq is always taken and b.ne never taken.  A region ends in
ret; entry labels at NMAX-N branches from the end give kernels of N branches
that all share the same tail code, so every size costs no extra text.

Regions (each emitted for b and bc, identical apart from the mnemonic, with
the same per-branch directions):
  mix     random 50/50 fixed direction, branch + 1 add      (8 B / branch)
  tk      all taken,                    branch + 1 add      (8 B / branch)
  nt      all not taken,                branch + 1 add      (8 B / branch)
  sparse  random 50/50 fixed direction, branch + 5 adds     (24 B / branch)
plus an evictor region (plain b, different random directions) that the driver
runs to flush the L1I / BTB / direction predictor before cold measurements.
"""
import random
import sys

DENSE_MAX = 512 * 1024
SPARSE_MAX = 128 * 1024
DENSE_SIZES = [4096, 16384, 65536, 262144, 524288]
SPARSE_SIZES = [4096, 16384, 65536, 131072]
EVICT = 256 * 1024


def region(name, br, nmax, sizes, dirs, filler):
    out = [f"\t.p2align 7\n"]
    entries = {nmax - n: n for n in sizes}
    for i in range(nmax):
        if i in entries:
            out.append(f"\t.globl _{name}_{entries[i]}\n_{name}_{entries[i]}:\n")
        cond = "eq" if dirs[i] else "ne"
        out.append(f"\t{br}.{cond} 3f\n" + "\tadd x10, x10, #1\n" * filler + "3:\n")
    out.append("\tret\n\n")
    return "".join(out)


def main():
    order = ("bc", "b") if "--bc-first" in sys.argv else ("b", "bc")
    rng = random.Random(2026)
    mix = [rng.random() < 0.5 for _ in range(DENSE_MAX)]
    sparse = [rng.random() < 0.5 for _ in range(SPARSE_MAX)]
    evict = [rng.random() < 0.5 for _ in range(EVICT)]
    src = ["// Generated by gen_cold.py; do not edit.\n\t.text\n",
           "\t.globl _hbc_enter\n\t.p2align 4\n_hbc_enter:\n\tcmp xzr, xzr\n\tbr x0\n\n",
           "\t.globl _hbc_empty\n_hbc_empty:\n\tret\n\n"]
    for br in order:
        src.append(region(f"kc_{br}_mix", br, DENSE_MAX, DENSE_SIZES, mix, 1))
        src.append(region(f"kc_{br}_tk", br, DENSE_MAX, DENSE_SIZES, [True] * DENSE_MAX, 1))
        src.append(region(f"kc_{br}_nt", br, DENSE_MAX, DENSE_SIZES, [False] * DENSE_MAX, 1))
        src.append(region(f"kc_{br}_sparse", br, SPARSE_MAX, SPARSE_SIZES, sparse, 5))
    src.append(region("kc_evict", "b", EVICT, [EVICT], evict, 1))
    sys.stdout.write("".join(src))


if __name__ == "__main__":
    main()
