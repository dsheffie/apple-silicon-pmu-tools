#!/usr/bin/env python3
"""Generate layoutbench.S: many copies of the data-dependent (random50) kernel.

COPIES pairs of b.cond / bc.cond copies of hbcbench's data kernel are placed
at varied offsets: pair c is preceded by 4096 + 68*c bytes of padding and its
two copies are separated by 64 + 36*c bytes, with b first for even c and bc
first for odd c. A placement effect is then spread across both variants, and
a hint effect shows up as a difference between the b and bc distributions.
Table: _lay[i] = {b copy, bc copy}; _lay_count = COPIES.
Usage: gen_layout.py KERNEL [copies] [seed]
KERNEL: data | single | alt | p8 | fpN | tkN (as in gen_hbc.py; tkN uses a
long-range loop branch so large N fits).
With a seed, padding and gaps are random multiples of 4 bytes (4096..8191 and
64..2111) instead of the fixed 68*c / 36*c progression.
"""
import random
import sys

COPIES = int(sys.argv[2]) if len(sys.argv) > 2 else 16
KERNEL = sys.argv[1] if len(sys.argv) > 1 else "data"
SEED = int(sys.argv[3]) if len(sys.argv) > 3 else None


def data_kernel(name, br):
    return (f"\t.globl _{name}\n_{name}:\n\tmov x14, #0\n"
            f"1:\tldrb w13, [x1, x14]\n\tadd x14, x14, #1\n\tand x14, x14, #0xffff\n"
            f"\tcmp w13, #0\n\t{br}.ne 2f\n\tadd x10, x10, #1\n"
            f"2:\tsub x0, x0, #1\n\tcbnz x0, 1b\n\tret\n")


def tk_kernel(name, br, n):
    body = "".join(f"\t{br}.eq 3{i % 2}f\n\tadd x10, x10, #1\n3{i % 2}:\n" for i in range(n))
    return (f"\t.globl _{name}\n_{name}:\n\tcmp xzr, xzr\n1:\n{body}"
            "\tsub x0, x0, #1\n\tcbz x0, 8f\n\tb 1b\n8:\tret\n")


def wrap(name, body):
    return f"\t.globl _{name}\n_{name}:\n{body}\tret\n"


def kernel(name, br):
    if KERNEL == "data":
        return data_kernel(name, br)
    if KERNEL.startswith("tk"):
        return tk_kernel(name, br, int(KERNEL[2:]))
    if KERNEL.startswith("fp"):
        n = int(KERNEL[2:])
        return wrap(name, "\tcmp xzr, xzr\n1:\n" + f"\t{br}.ne 9f\n\tadd x10, x10, #1\n" * n +
                    "\tsub x0, x0, #1\n\tcbnz x0, 1b\n9:\n")
    if KERNEL == "single":
        return wrap(name, f"\tcmp xzr, xzr\n1:\t{br}.ne 2f\n\tadd x10, x10, #1\n"
                    "\tsub x0, x0, #1\n\tcbnz x0, 1b\n2:\n")
    if KERNEL == "alt":
        return wrap(name, f"1:\teor x11, x11, #1\n\tcmp x11, #0\n\t{br}.ne 2f\n\tadd x10, x10, #1\n"
                    "2:\tsub x0, x0, #1\n\tcbnz x0, 1b\n")
    if KERNEL == "p8":
        return wrap(name, f"1:\tadd x12, x12, #1\n\tand x13, x12, #7\n\tcmp x13, #0\n\t{br}.eq 2f\n"
                    "\tadd x10, x10, #1\n2:\tsub x0, x0, #1\n\tcbnz x0, 1b\n")
    raise SystemExit(f"unknown kernel {KERNEL}")


def main():
    src = ["// Generated by gen_layout.py; do not edit.\n\t.text\n\t.p2align 14\n"]
    rng = random.Random(SEED)
    for c in range(COPIES):
        pad, gap = (4096 + 68 * c, 64 + 36 * c) if SEED is None else \
            (4096 + 4 * rng.randrange(1024), 64 + 4 * rng.randrange(512))
        src.append(f"\t.space {pad}\n")
        order = ("b", "bc") if c % 2 == 0 else ("bc", "b")
        src.append(kernel(f"l_{order[0]}_{c}", order[0]))
        src.append(f"\t.space {gap}\n")
        src.append(kernel(f"l_{order[1]}_{c}", order[1]))
    src.append("\t.section __DATA,__data\n\t.p2align 3\n\t.globl _lay_count\n"
               f"_lay_count:\n\t.quad {COPIES}\n\t.globl _lay\n_lay:\n")
    for c in range(COPIES):
        src.append(f"\t.quad _l_b_{c}, _l_bc_{c}\n")
    print("".join(src), end="")


if __name__ == "__main__":
    main()
